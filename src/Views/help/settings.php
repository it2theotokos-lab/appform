<h5 class="text-white mb-2"><i class="fa-solid fa-gears text-primary me-2"></i> Οδηγίες: Κέντρο Διαχείρισης Συστήματος</h5>
<p>Διαμόρφωση γενικών παραμέτρων, λήψη αντιγράφων ασφαλείας, ρυθμίσεις SMTP και demo data.</p>
<ul>
    <li><strong>Γενικές Ρυθμίσεις:</strong> Όνομα εφαρμογής, όρια αρχείων κλπ.</li>
    <li><strong>Backup:</strong> Χειροκίνητη λήψη και έλεγχος ακεραιότητας (SHA256).</li>
    <li><strong>Επαναφορά (Restore):</strong> Οδηγός επαναφοράς με checksum integrity validation, mandatory emergency backups και αυτόματο rollback σε περίπτωση αποτυχίας.</li>
    <li><strong>Demo Data:</strong> Εισαγωγή ή διαγραφή εικονικών δεδομένων δοκιμών.</li>
    <li><strong>SMTP:</strong> Ρυθμίσεις εξωτερικού mail server.</li>
</ul>
